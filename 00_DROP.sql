SET SERVEROUTPUT ON;

DECLARE
    PROCEDURE p (p_cmd IN VARCHAR2) IS
    BEGIN
        EXECUTE IMMEDIATE p_cmd;
    EXCEPTION
        WHEN OTHERS THEN
            NULL; -- objeto inexistente: segue o reset
    END;
BEGIN
    -- gatilhos
    p('DROP TRIGGER TRG_DF_AUDITORIA_CASO');
    p('DROP TRIGGER TRG_DF_CASO_VALIDA');
    -- pacotes (06_PACKAGES.sql)
    p('DROP PACKAGE PKG_FARMACIA_POPULAR');
    p('DROP PACKAGE PKG_CASOS');
    p('DROP PACKAGE PKG_ELEGIBILIDADE');
    p('DROP PACKAGE PKG_AUDITORIA');
    -- funcoes e procedures avulsas (05_FUNCOES_PROCEDURES_GATILHOS.sql)
    p('DROP FUNCTION FN_AVALIAR_ELEGIBILIDADE');
    p('DROP FUNCTION FN_RENDA_PER_CAPITA_SM');
    p('DROP PROCEDURE PRC_ABRIR_CASOS');
    p('DROP PROCEDURE PRC_ATUALIZAR_STATUS_CASO');
    p('DROP PROCEDURE PRC_AVALIAR_DIREITO');
    -- procedures de carga (02_PROCEDURES.sql)
    p('DROP PROCEDURE PRC_CARGA_CRITERIO');
    p('DROP PROCEDURE PRC_CARGA_DIREITO');
    p('DROP PROCEDURE PRC_CARGA_LAUDO');
    p('DROP PROCEDURE PRC_CARGA_DOCUMENTO');
    p('DROP PROCEDURE PRC_CARGA_PESSOA');
    p('DROP PROCEDURE PRC_CARGA_SALARIO_MINIMO');
    p('DROP PROCEDURE PRC_CARGA_USUARIO');
    p('DROP PROCEDURE PRC_CARGA_MEDICAMENTO_FP');
    -- tabelas: filhas primeiro, depois as pais
    p('DROP TABLE T_DF_RECEITA_ITEM CASCADE CONSTRAINTS PURGE');
    p('DROP TABLE T_DF_RECEITA CASCADE CONSTRAINTS PURGE');
    p('DROP TABLE T_DF_MEDICAMENTO_FP CASCADE CONSTRAINTS PURGE');
    p('DROP TABLE T_DF_AUDITORIA_CASO CASCADE CONSTRAINTS PURGE');
    p('DROP TABLE T_DF_ORIENTACAO CASCADE CONSTRAINTS PURGE');
    p('DROP TABLE T_DF_CASO CASCADE CONSTRAINTS PURGE');
    p('DROP TABLE T_DF_LAUDO CASCADE CONSTRAINTS PURGE');
    p('DROP TABLE T_DF_DOCUMENTO CASCADE CONSTRAINTS PURGE');
    p('DROP TABLE T_DF_CRITERIO_DIREITO CASCADE CONSTRAINTS PURGE');
    p('DROP TABLE T_DF_DIREITO CASCADE CONSTRAINTS PURGE');
    p('DROP TABLE T_DF_PESSOA CASCADE CONSTRAINTS PURGE');
    p('DROP TABLE T_DF_SALARIO_MINIMO CASCADE CONSTRAINTS PURGE');
    p('DROP TABLE T_DF_USUARIO CASCADE CONSTRAINTS PURGE');
    p('DROP TABLE T_DF_LOG_ERRO CASCADE CONSTRAINTS PURGE');
    DBMS_OUTPUT.PUT_LINE('Reset concluido: todos os objetos T_DF_* removidos.');
END;
